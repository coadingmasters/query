<h2 id="hiding">Hiding more than usual</h2>

<p>
    A cat that suddenly wants to be under the bed, behind the sofa, or in a
    closet rather than in their usual spots is telling you something even
    if nothing else looks different yet. Hiding is one of the most reliable
    early behavioral signs precisely because it costs a cat nothing to do
    and requires no visible symptom at all.
</p>

