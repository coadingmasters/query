<p>
    "Indoor formula" on a bag of cat food describes a general approach, not
    a regulated nutritional standard. What actually matters for an indoor
    cat is closer to what matters for any cat: the right calories for how
    active they really are, a protein-first ingredient list, and a formula
    matched to their life stage.
</p>

<p>
    This guide is written from published veterinary sources, named and
    linked as they come up and listed again at the bottom.
</p>

<h2 id="indoor-formula">What does "indoor formula" actually mean?</h2>

<p>
    There is no official definition. In practice, foods marketed as indoor
    formulas tend to be somewhat lower in calories and higher in fiber for
    hairball control, on the reasoning that indoor cats are typically less
    active than cats with outdoor access. That is a reasonable starting
    assumption, but it is a marketing category rather than a standard every
    brand follows the same way, so reading the actual label tells you more
    than the word on the front of the bag.
</p>

<h2 id="what-to-look-for">What to actually look for on the label</h2>

<p>
    A named animal protein, such as chicken, turkey or salmon, should be
    the first ingredient. Cats are obligate carnivores regardless of
    whether they ever go outside, and that does not change based on
    lifestyle. The label should also state that the food is complete and
    balanced for your cat's life stage, whether that is kitten, adult or
    senior, since life stage affects nutritional needs far more than
    indoor versus outdoor does.
</p>

