<p>
    Cats are good at looking fine right up until they are not. It is not
    stoicism, it is instinct: a wild cat that looks weak is a target, so the
    ones we live with still default to hiding pain and illness rather than
    showing it. That is exactly what makes the early signs worth knowing,
    because by the time a cat looks obviously unwell, whatever is wrong has
    usually had time to progress.
</p>

<p>
    None of the twelve signs below confirm anything on their own. What
    matters is a change from what is normal for your own cat, and whether
    more than one of them shows up together.
</p>

<p>
    This guide is written from published veterinary sources, named and
    linked as they come up and listed again at the bottom. It is not an
    examination of your own cat, and nothing here replaces one.
</p>

<h2 id="hiding-illness">Why cats hide being sick</h2>

<p>
    In the wild, a cat that looks sick or slow is the one a predator picks
    off, and the instinct never went away just because the cat now lives on
    a sofa. That is why the earliest signs are usually behavioral rather
    than dramatic: a little less interested in food, a little quieter, a
    spot they do not normally sleep in. Cats mask discomfort well enough
    that owners often only notice once a second or third sign appears.
</p>

<h2 id="emergency">When is this an emergency?</h2>

<p>
    Some of the signs below can wait for a routine appointment. Others
    cannot. If any of these are happening right now, call an emergency vet
    rather than waiting:
</p>

<ul>
    <li>Straining in the litter box with little or no urine coming out</li>
    <li>Labored, open-mouthed, or noisy breathing</li>
    <li>Collapse, or a cat who will not get up</li>
    <li>Repeated vomiting, especially if nothing is staying down</li>
    <li>Bleeding from anywhere, or a swollen, painful belly</li>
    <li>A cat who will not respond to you at all</li>
</ul>

<p>
    A blocked bladder in particular, more common in male cats, can become
    fatal within a day if it is not treated. That specific combination,
    straining with little or nothing coming out, is one of the few feline
    symptoms that genuinely cannot wait until morning.
</p>

