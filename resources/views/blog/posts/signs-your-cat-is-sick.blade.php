<h2 id="lethargic">Low energy or seeming lethargic</h2>

<p>
    Every cat has an off day. What is worth noting is a cat who is
    consistently less interested in play, in greeting you, or in moving
    around than they normally are, especially alongside any other sign on
    this list. Lethargy on its own is vague; lethargy plus almost anything
    else is a reason to look closer.
</p>

<h2 id="vomiting">Vomiting</h2>

<p>
    Cats vomit more casually than most owners expect, and an occasional
    hairball or a too-fast meal coming back up once is not usually cause for
    alarm. Repeated vomiting, vomiting alongside not eating, or vomiting
    that contains blood is different, and any of those is worth a same-day
    call to the vet rather than a wait-and-see approach.
</p>

<h2 id="losing-weight">Losing weight</h2>

<p>
    Weight loss in a cat who is eating normally is one of the more telling
    signs on this list, because it points at something happening beneath
    the surface rather than an obvious cause. It is also one of the easiest
    signs to miss in a cat with a thick coat, since the change is felt more
    than seen at first.
</p>

<p>
    This matters more in older cats, where gradual weight loss is
    frequently one of the earliest signs of kidney disease, an overactive
    thyroid, or diabetes. If you are not sure what life stage your cat is
    in, our <a href="{{ route('tools.cat-age-calculator') }}">cat age calculator</a>
    converts their age into human years and the AAFP life stage that
    determines how often they should be seeing a vet in the first place.
</p>

<h2 id="thirst">Drinking more water than usual</h2>

<p>
    A cat drinking noticeably more, and often urinating more as a result, is
    a classic early sign of diabetes, kidney disease, or an overactive
    thyroid, particularly in cats over seven or eight. It is easy to miss
    because increased thirst does not look like illness. Refilling the water
    bowl more often than you used to is worth mentioning at the next vet
    visit even if nothing else seems wrong.
</p>

<h2 id="litter-box">Changes in the litter box</h2>

<p>
    Straining, going more or less often, blood in the urine or stool, or a
    sudden move away from the litter box are all worth attention. Straining
    with little or nothing coming out is the one to treat as an emergency,
    not a behavior problem, since it can point at a blocked bladder, which
    is genuinely life-threatening within a day.
</p>

<h2 id="breathing">Breathing changes</h2>

<p>
    Fast, labored, open-mouthed breathing, or breathing with visible effort,
    is always worth same-day attention in a cat. If what you are actually
    seeing is sneezing, a runny nose or watery eyes rather than labored
    breathing itself, that is more likely a respiratory infection than an
    emergency; our <a href="{{ route('blog.show', 'why-is-my-cat-sneezing') }}">guide to cat sneezing</a>
    covers that specific pattern and when it needs a vet.
</p>

<h2 id="grooming">Changes in grooming or coat</h2>

<p>
    Cats are fastidious groomers, and a cat who stops, whose coat turns
    dull, greasy or matted, or who over-grooms one spot until the fur thins,
    is showing you something. Under-grooming often points at pain or
    nausea making the effort not worth it; over-grooming one area can be
    stress, or it can be the cat's way of drawing attention to somewhere
    that hurts.
</p>

<h2 id="weight-gain">Sudden weight gain or a swollen belly</h2>

<p>
    Weight gain over months is usually just diet. Weight gain, or a visibly
    swollen or firm belly, over days is different, and can point at fluid
    buildup from several serious conditions. A belly that looks bloated or
    feels hard, especially paired with reduced appetite, is worth a vet
    visit rather than a wait.
</p>

<h2 id="vocalizing">Vocalizing more, or differently</h2>

<p>
    A cat who suddenly yowls more, especially at night, or whose meow
    changes in pitch or urgency, is often trying to tell you something.
    In older cats this is sometimes linked to cognitive changes or high
    blood pressure; in any cat, a new or unusual vocal pattern is worth
    mentioning to a vet, particularly if it started suddenly.
</p>

<h2 id="pain">Signs of pain</h2>

<p>
    Cats do not limp and whimper the way dogs often do. Pain in a cat looks
    like reluctance to jump onto a usual spot, hunching, growling or
    flinching when touched in a specific area, hiding, or simply moving less.
    Because these signs overlap with several others on this list, pain is
    frequently the thing tying two or three of them together rather than a
    standalone symptom.
</p>

<h2 id="what-to-do">What to do next</h2>

<p>
    One mild sign in a cat who is otherwise acting normally is worth
    watching for a day. Two or more signs together, or anything from the
    emergency list above, is worth a call now rather than a wait. When you
    do call, describe what changed and when, since a vet works from a
    comparison to your own cat's normal rather than a general checklist.
</p>

