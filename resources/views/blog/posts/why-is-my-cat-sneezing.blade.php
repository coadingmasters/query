<p>
    Cats sneeze for the same reason people do: something tickled the inside of
    their nose. Dust from the litter tray, a gust of cold air, a strong
    perfume, and it is over in a second and forgotten. That is most sneezing,
    and it needs nothing from you.
</p>

<p>
    What is worth paying attention to is the pattern around it. A single
    sneeze from an otherwise normal cat is not the same thing as sneezing that
    keeps happening, or that arrives with a runny nose, watery eyes or a cat
    who has gone off their food. Here is how to tell the difference.
</p>

<h2 id="normal">Is it normal for a cat to sneeze?</h2>

<p>
    Yes, occasionally. A cat's nose is at floor level and close to whatever it
    is investigating, so it picks up more dust, pollen and fine litter
    particles than yours does. One or two sneezes while your cat is otherwise
    playing, eating and behaving normally is not a sign of anything.
</p>

<p>
    What changes the picture is frequency and company. Sneezing that repeats
    through the day, that continues for more than a day or two, or that
    arrives alongside discharge, is no longer just dust.
</p>

<h2 id="keeps-sneezing">Why does my cat keep sneezing?</h2>

<p>
    Sneezing that keeps coming back usually means one of two things: an
    ongoing irritant, or an infection.
</p>

<p>
    An irritant is the easier one to rule out. Scented candles, air
    fresheners, cleaning sprays, cigarette smoke and dusty, scented litter are
    the most common causes, and switching the litter or airing the room for a
    day is often enough to tell you whether that was it.
</p>

<p>
    If nothing has changed in the house, an upper respiratory infection is the
    more likely explanation. Feline herpesvirus and calicivirus are extremely
    common in cats, particularly cats who spent time in a shelter or came from
    a large litter, and both produce cold-like symptoms that center on
    sneezing.
</p>

<h2 id="acting-normal">My cat is sneezing but acting completely normal. Should I worry?</h2>

<p>
    Generally, no. A cat that is still eating, drinking, playing and seeking
    you out despite a mild sneeze is not showing signs of a serious problem.
    The behavior around the sneezing tells you more than the sneezing itself.
</p>

<p>
    Keep an eye on it rather than dismissing it. Mild viral infections
    sometimes start exactly this way, with a few days of sneezing and nothing
    else, before other symptoms appear or before it resolves on its own. If
    your cat is still acting completely normal after three or four days, that
    is reassuring; if eating or energy drops off, it is time to call the vet.
</p>

<h2 id="runny-nose">My cat is sneezing and has a runny nose or watery eyes</h2>

<p>
    This combination is the clearest sign of an upper respiratory infection.
    What the discharge looks like tells you roughly how far along it is:
</p>

<ul>
    <li><strong>Clear discharge</strong> is more consistent with a viral infection in its early stages, the feline equivalent of a common cold.</li>
    <li><strong>Thick, yellow or green discharge</strong> usually means a secondary bacterial infection has set in on top of the virus, and it generally needs antibiotics from a vet rather than time alone.</li>
    <li><strong>Discharge from one nostril only</strong> is different again, and points more toward something physically stuck in the nose, a tooth root problem, or in older cats, a nasal polyp.</li>
</ul>

<p>
    Watery eyes alongside sneezing is common with the same viral infections,
    since feline herpesvirus affects the eyes as often as the nose.
</p>

<h2 id="kitten">Why is my kitten sneezing so much?</h2>

<p>
    Kittens catch upper respiratory infections easily, and their symptoms
    tend to hit harder than an adult cat's. A kitten's immune system has not
    built up the same resistance yet, which is why sneezing, watery eyes and
    congestion spread quickly through shelters and multi-kitten litters.
</p>

<p>
    Take a kitten who stops eating more seriously than you would an adult
    with the same symptoms. A blocked nose can be enough to put a kitten off
    food because they cannot smell it, and kittens dehydrate and lose weight
    far faster than adult cats. A vet visit is worth it sooner rather than
    later for a kitten who has gone off food for even half a day.
</p>

<p>
    Kittens change fast in general, and knowing roughly what stage yours is
    at makes a lot of their health and behavior easier to read. Our
    <a href="{{ route('tools.cat-age-calculator') }}">cat age calculator</a>
    converts an age into human years and the life stage they are in.
</p>

<h2 id="causes">What causes a cat to sneeze?</h2>

<p>Roughly in order of how often each one turns out to be the cause:</p>

<ol>
    <li><strong>Viral upper respiratory infection.</strong> Feline herpesvirus and calicivirus, by far the most common cause of repeated sneezing.</li>
    <li><strong>Environmental irritants.</strong> Dust, scented litter, cleaning products, smoke and strong perfume.</li>
    <li><strong>Allergies.</strong> Less common in cats than in people, but they do happen, usually alongside itchy skin or watery eyes.</li>
    <li><strong>A foreign body.</strong> A blade of grass or a seed caught in the nose causes sudden, intense, usually one-sided sneezing.</li>
    <li><strong>Dental disease.</strong> A tooth root abscess near the nasal passage can produce sneezing and discharge that looks respiratory but is not.</li>
    <li><strong>Nasal polyps or, rarely, a tumour.</strong> Usually in older cats, and usually chronic rather than sudden, with sneezing that persists for weeks.</li>
</ol>

<p>
    A vet works through this list roughly in this order too, which is part of
    why a physical exam matters more than guessing from symptoms alone.
</p>

<h2 id="vet">When should I take my sneezing cat to the vet?</h2>

<p>Call the vet if any of the following apply:</p>

<ul>
    <li>Sneezing has continued for more than two or three days</li>
    <li>There is any blood in the sneeze or the discharge</li>
    <li>Discharge has turned yellow or green</li>
    <li>Only one nostril is affected</li>
    <li>Your cat has stopped eating, or seems unusually quiet or lethargic</li>
    <li>Breathing looks labored, or your cat is breathing through their mouth</li>
    <li>It is a kitten, a senior cat, or a cat with an existing health condition</li>
</ul>

<p>
    None of these need to wait for a routine appointment. A same-day or
    next-day visit is the right call for any of them, and blood in a sneeze
    specifically is worth calling ahead about rather than just booking in.
</p>

<h2 id="home-care">Can I do anything at home while I wait?</h2>

<p>
    A little, and only as comfort rather than treatment. A humidifier, or a
    few minutes sitting with your cat in a steamy bathroom, can loosen
    congestion and make breathing easier. Gently wiping discharge away from
    the nose and eyes with a damp cloth keeps your cat more comfortable and
    stops it crusting.
</p>

<p>
    What not to do is reach for a human cold remedy. Decongestants,
    antihistamines and pain relievers made for people are frequently unsafe
    for cats, and several common ones are outright toxic. If your cat needs
    medication, it needs to come from a vet who has actually examined them.
</p>

