<h2 id="calories">Getting the calories right</h2>

<p>
    Indoor cats generally burn fewer calories than cats with regular
    outdoor activity, and weight gain is one of the more common issues
    among indoor cats as a result. Rather than relying on a bag's general
    "indoor" positioning, working out your specific cat's daily calorie
    needs from their weight gives a far more accurate portion. Our
    <a href="{{ route('blog.show', 'how-much-should-i-feed-my-cat') }}">feeding guide</a>
    has the formula vets use and a reference table by weight.
</p>

<h2 id="wet-or-dry">Wet or dry food for an indoor cat?</h2>

<p>
    Both can be complete diets, and the choice matters less than getting
    the calories right within whichever you pick. Wet food does have one
    specific advantage worth knowing: it adds meaningful water intake,
    which helps toward diluting urine, and indoor cats are somewhat more
    prone to concentrated urine and the urinary tract issues that can
    follow. Dry food is more convenient and typically cheaper per calorie,
    and plenty of indoor cats do fine on it with adequate water intake from
    a bowl or fountain.
</p>

<h2 id="hairballs">Hairball control: food or brushing?</h2>

<p>
    Indoor cats tend to groom more, simply from having less else to do, so
    hairballs come up more often as a concern. A fiber-adjusted hairball
    formula can help, but regular brushing does more for most cats than a
    specialized food does. A cat bringing up hairballs frequently, or
    straining without producing one, is worth mentioning to a vet rather
    than assuming a food swap will fix it.
</p>

<h2 id="life-stage">Matching food to life stage</h2>

<p>
    A kitten, an adult and a senior cat have meaningfully different
    nutritional needs, and that difference matters more than whether a cat
    goes outside. If you are not sure where your cat sits, our
    <a href="{{ route('tools.cat-age-calculator') }}">cat age calculator</a>
    converts their age into the life stage that should be driving the food
    choice.
</p>

<h2 id="same-food">Can indoor and outdoor cats eat the same food?</h2>

<p>
    Yes, as long as the portion is adjusted for how active each cat
    actually is. A complete, balanced adult formula works for both an
    indoor and an outdoor cat; what changes is how much of it each one
    needs, not which bag it comes from.
</p>
