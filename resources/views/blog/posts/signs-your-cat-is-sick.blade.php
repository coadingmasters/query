<p>
    Treat this as a rough guide, not a diagnosis. It exists to help you
    decide how quickly to act, not to replace an exam.
</p>

<h2 id="not-eating">Not eating, or eating much less</h2>

<p>
    A change in appetite is usually the first thing owners notice, and it
    can mean almost anything, from a minor stomach upset to dental pain to
    something more serious. What matters most is duration: a cat that skips
    one meal and is otherwise normal is not an emergency. A cat that has not
    eaten in over 24 hours, particularly one who is already thin, is.
</p>

